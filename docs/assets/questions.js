/** Số phút mô phỏng bài thi (theo trang chứng chỉ: 90 phút). */
export const MOCK_DURATION_MIN = 90;

/** Số câu trong bài thi thử (ước lượng luyện tập — đề thật có thể khác). */
export const MOCK_QUESTION_COUNT = 40;

export function pickMockQuestions(seed) {
  const copy = [...questions];
  const rng = mulberry32(seed);
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, Math.min(MOCK_QUESTION_COUNT, copy.length));
}

function mulberry32(a) {
  return function () {
    let t = (a += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
